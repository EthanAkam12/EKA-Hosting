// Turns a published site into plain files that work on any normal web host:
//
//   index.html, <page>/index.html   the pages (CSS inlined, no JavaScript)
//   media/...                       images the pages use
//   contact.php                     emails contact-form messages to the owner
//   404.html, .htaccess, robots.txt, sitemap.xml (when the domain is known)
//
// Used by "Download site as files" and by "Publish to hosting" (FTP).

import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { renderPage, sitemapXml } from "../shared/render.js";

export async function buildStaticSite({ site, siteId, mediaDir, formEmail = "", domain = "" }) {
  const files = [];
  const add = (p, content) => files.push({ path: p, content: Buffer.isBuffer(content) ? content : Buffer.from(content) });
  const mediaPrefix = `/_m/${siteId}/`;
  const usedMedia = new Set();

  // Point image URLs at the exported media folder and remember which files
  // are used, so only those get uploaded.
  const fixMedia = (html) =>
    html.replace(new RegExp(escapeRegExp(mediaPrefix) + "([\\w.-]+)", "g"), (_, file) => {
      usedMedia.add(file);
      return `/media/${file}`;
    });

  const hasForm = site.pages.some((p) => p.sections.some((s) => s.columns.some((c) => c.blocks.some((b) => b.type === "form"))));

  for (const page of site.pages) {
    const canonical = domain ? `https://${domain}/${page.slug === "index" ? "" : `${page.slug}/`}` : undefined;
    const html = fixMedia(renderPage(site, page, { base: "/", formAction: "/contact.php", canonical }));
    add(page.slug === "index" ? "index.html" : `${page.slug}/index.html`, html);
  }
  // Logo and other images referenced outside page bodies (e.g. the header).
  fixMedia(JSON.stringify(site));

  for (const file of usedMedia) {
    const variants = [file];
    if (file.endsWith("-o.webp")) variants.push(file.replace(/-o\.webp$/, "-o-sm.webp"));
    for (const name of variants) {
      try {
        add(`media/${name}`, await fs.readFile(path.join(mediaDir, name)));
      } catch {
        // Missing on disk (deleted image still referenced): skip it.
      }
    }
  }

  add("404.html", notFoundPage(site));
  if (domain) add("sitemap.xml", sitemapXml(site, `https://${domain}`));
  add("robots.txt", `User-agent: *\nAllow: /\n${domain ? `Sitemap: https://${domain}/sitemap.xml\n` : ""}`);
  add(".htaccess", HTACCESS);
  if (hasForm) add("contact.php", contactPhp(site, formEmail));

  return files;
}

export function fileHash(buf) {
  return crypto.createHash("sha1").update(buf).digest("hex");
}

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

function notFoundPage(site) {
  return `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Page not found | ${escapeHtml(site.name)}</title><style>body{font:16px/1.6 system-ui,sans-serif;display:grid;place-items:center;min-height:100vh;margin:0;color:#222;text-align:center;padding:20px}a{color:${site.theme.colors.primary}}</style><div><h1>Page not found</h1><p>Sorry, that page doesn't exist. <a href="/">Go to the home page</a></p></div></html>`;
}

// Apache settings most shared hosts honour: compression, caching and the 404
// page. Each block is wrapped in IfModule so a host without that module just
// ignores it instead of erroring.
const HTACCESS = `# Added by EKA Hosting
ErrorDocument 404 /404.html
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain application/javascript image/svg+xml
</IfModule>
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/html "access plus 5 minutes"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/gif "access plus 1 year"
</IfModule>
<Files "contact.php">
  <IfModule mod_headers.c>
    Header set Cache-Control "no-store"
  </IfModule>
</Files>
`;

// A small, careful PHP mailer. The recipient is fixed at export time, never
// taken from the form, so the script can't be abused to send spam elsewhere.
function contactPhp(site, formEmail) {
  const forms = {};
  for (const page of site.pages) {
    for (const s of page.sections) for (const c of s.columns) for (const b of c.blocks) {
      if (b.type === "form") forms[b.id] = { labels: b.props.fields.map((f, i) => f.label || `Field ${i + 1}`), page: page.slug };
    }
  }
  const pages = Object.fromEntries(site.pages.map((p) => [p.slug, p.slug === "index" ? "/" : `/${p.slug}/`]));
  const php = (v) => `json_decode(base64_decode('${Buffer.from(JSON.stringify(v)).toString("base64")}'), true)`;
  return `<?php
// Contact form handler, generated by EKA Hosting for ${site.name.replace(/[\r\n*/]/g, " ")}.
// Re-publishing the site replaces this file.

$to      = ${php(formEmail)};
$site    = ${php(site.name)};
$forms   = ${php(forms)};
$pages   = ${php(pages)};

function back($pages, $page, $hash) {
  $path = isset($pages[$page]) ? $pages[$page] : '/';
  header('Location: ' . $path . $hash, true, 303);
  exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') back($pages, 'index', '');

$block = isset($_POST['_block']) ? (string) $_POST['_block'] : '';
$page  = isset($_POST['_page']) ? (string) $_POST['_page'] : 'index';
if (!isset($forms[$block])) back($pages, $page, '');
$form = $forms[$block];

// Bots fill in the hidden "website" field. Pretend it worked.
if (!empty($_POST['website'])) back($pages, $form['page'], '#sent-' . $block);

// Simple rate limit: 5 messages per visitor per 10 minutes.
$dir = sys_get_temp_dir() . '/eka-forms';
if (!is_dir($dir)) @mkdir($dir, 0700, true);
$key = $dir . '/' . md5((isset($_SERVER['REMOTE_ADDR']) ? $_SERVER['REMOTE_ADDR'] : '') . '|' . __FILE__);
$hits = @json_decode(@file_get_contents($key), true);
if (!is_array($hits)) $hits = array();
$now = time();
$hits = array_values(array_filter($hits, function ($t) use ($now) { return $now - $t < 600; }));
if (count($hits) >= 5) { http_response_code(429); echo 'Too many messages. Please try again in a few minutes.'; exit; }
$hits[] = $now;
@file_put_contents($key, json_encode($hits));

$lines = array();
$replyTo = '';
foreach ($form['labels'] as $i => $label) {
  $value = isset($_POST['field_' . $i]) ? trim((string) $_POST['field_' . $i]) : '';
  $value = mb_substr($value, 0, 5000);
  if ($value === '') continue;
  $lines[] = $label . ":\\n" . $value . "\\n";
  if ($replyTo === '' && filter_var($value, FILTER_VALIDATE_EMAIL)) $replyTo = $value;
}
if (!$lines) back($pages, $form['page'], '#f-' . $block);

if ($to !== '' && filter_var($to, FILTER_VALIDATE_EMAIL)) {
  $host = isset($_SERVER['HTTP_HOST']) ? $_SERVER['HTTP_HOST'] : 'localhost';
  $host = preg_replace('/:\\d+$/', '', $host);               // drop any :port
  $host = preg_replace('/^www\\./', '', preg_replace('/[^a-z0-9.-]/i', '', $host));
  $clean = function ($s) { return trim(str_replace(array("\\r", "\\n"), ' ', $s)); };
  $headers = array(
    'From: ' . $clean($site) . ' website <website@' . $host . '>',
    'Content-Type: text/plain; charset=UTF-8',
  );
  if ($replyTo !== '') $headers[] = 'Reply-To: ' . $clean($replyTo);
  $subject = '=?UTF-8?B?' . base64_encode('New message from your website') . '?=';
  $body = "You have a new message from the contact form on your website.\\n\\n" . implode("\\n", $lines) . "\\n--\\nSent " . date('j M Y, H:i') . ".";
  @mail($to, $subject, $body, implode("\\r\\n", $headers));
}

back($pages, $form['page'], '#sent-' . $block);
`;
}
