// "Download as CubeCart skin": turns a site designed in the builder into a
// CubeCart 6.8+ skin, so a customer's shop runs on CubeCart (basket, payments,
// stock, orders) but looks like the site you designed.
//
// It starts from the Heirloom skin in cubecart-skins/heirloom (built on
// CubeCart's Atrium skin) and adds a generated css/eka-theme.css that maps the
// site's colours, fonts and corner rounding onto the skin's --cc-* tokens.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FONT_CHOICES } from "../shared/schema.js";

const BASE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "cubecart-skins", "heirloom");
const SKIP = new Set(["docs/HOMEPAGE.html", "INSTALL.md"]);

let sharp = null;
try {
  sharp = (await import("sharp")).default;
} catch {
  // Logo is then copied as-is (only if it's already a PNG/JPG).
}

function mix(hex, toward, amount) {
  const p = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
  const [a, b] = [p(hex), p(toward)];
  return "#" + a.map((v, i) => Math.round(v + (b[i] - v) * amount).toString(16).padStart(2, "0")).join("");
}

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
const onColour = (hex) => (luminance(hex) > 0.4 ? "#111111" : "#ffffff");

export function themeCss(site) {
  const c = site.theme.colors;
  const head = FONT_CHOICES[site.theme.fonts.heading] || FONT_CHOICES.system;
  const body = FONT_CHOICES[site.theme.fonts.body] || FONT_CHOICES.system;
  const google = [...new Set([head.google, body.google].filter(Boolean))];
  const p = c.primary;
  const brand = {
    50: mix(p, "#ffffff", 0.93), 100: mix(p, "#ffffff", 0.85), 200: mix(p, "#ffffff", 0.7), 300: mix(p, "#ffffff", 0.5),
    400: mix(p, "#ffffff", 0.3), 500: mix(p, "#ffffff", 0.14), 600: p, 700: mix(p, "#000000", 0.18),
    800: mix(p, "#000000", 0.32), 900: mix(p, "#000000", 0.45), 950: mix(p, "#000000", 0.6),
  };
  const steps = { 50: 0, 100: 0.05, 200: 0.12, 300: 0.2, 400: 0.42, 500: 0.55, 600: 0.66, 700: 0.75, 800: 0.85, 900: 0.93, 950: 1 };
  const ink = Object.fromEntries(Object.entries(steps).map(([k, t]) => [k, mix(c.background, c.text, t)]));
  const radius = Math.max(0, Math.min(24, Number(site.theme.radius) || 0));
  const lines = [
    `/* Generated by EKA Hosting from the "${site.name.replace(/\*\//g, "")}" design. Re-download the skin to update it. */`,
    ...(google.length ? [`@import url("https://fonts.googleapis.com/css2?${google.map((f) => `family=${f}`).join("&")}&display=swap");`] : []),
    ":root {",
    ...Object.entries(brand).map(([k, v]) => `  --cc-brand-${k}: ${v};`),
    `  --cc-brand-fg: ${onColour(p)};`,
    ...Object.entries(ink).map(([k, v]) => `  --cc-ink-${k}: ${v};`),
    `  --hl-brass: ${c.accent};`,
    `  --hl-brass-light: ${mix(c.accent, "#ffffff", 0.35)};`,
    `  --hl-mat: ${mix(c.background, "#ffffff", 0.6)};`,
    `  --cc-chrome: ${c.dark};`,
    `  --cc-chrome-hover: ${mix(c.dark, "#ffffff", 0.12)};`,
    `  --cc-chrome-fg: ${mix(onColour(c.dark), c.dark, 0.06)};`,
    `  --cc-chrome-muted: ${mix(onColour(c.dark), c.dark, 0.3)};`,
    `  --cc-chrome-border: ${mix(c.dark, "#ffffff", 0.15)};`,
    `  --cc-chrome-sale: ${mix(c.accent, "#ffffff", 0.25)};`,
    `  --cc-footer: ${c.dark};`,
    `  --cc-footer-fg: ${mix(onColour(c.dark), c.dark, 0.08)};`,
    `  --cc-footer-muted: ${mix(onColour(c.dark), c.dark, 0.3)};`,
    `  --cc-footer-border: ${mix(c.dark, "#ffffff", 0.15)};`,
    `  --cc-footer-hover: ${mix(c.accent, "#ffffff", 0.25)};`,
    `  --cc-star: ${c.accent};`,
    `  --cc-radius: ${radius}px;`,
    `  --cc-radius-lg: ${radius + 3}px;`,
    `  --cc-font-serif: ${head.stack};`,
    `  --cc-font-sans: ${body.stack};`,
    "}",
    // Body text in the site's body font.
    "body { font-family: var(--cc-font-sans); }",
    "",
  ];
  return lines.join("\n");
}

// The homepage banner, written from the site's own hero and features.
export function homepageHtml(site) {
  const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  const blocks = (site.pages[0]?.sections || []).flatMap((s) => s.columns.flatMap((c) => c.blocks));
  const heading = blocks.find((b) => b.type === "heading")?.props.text || site.name;
  const textHtml = blocks.find((b) => b.type === "text")?.props.html || "";
  const intro = textHtml.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim() || `Welcome to ${site.name}.`;
  const cards = blocks.filter((b) => b.type === "card" && b.props.title).slice(0, 4);
  const promises = cards.length
    ? cards.map((c) => `      <div><strong>${esc(c.props.title)}</strong>${esc(c.props.text)}</div>`).join("\n")
    : ["One of a kind|Each item is the only one we have.", "Honestly described|Age, wear and repairs, all noted.", "Carefully packed|Wrapped by hand and fully insured.", "Here to help|Questions? Just get in touch."]
        .map((x) => { const [t, d] = x.split("|"); return `      <div><strong>${t}</strong>${d}</div>`; }).join("\n");
  return `<div class="hl-welcome">
  <div>
    <div class="hl-eyebrow">${esc(site.name)}</div>
    <h2>${esc(heading)}</h2>
    <p>${esc(intro)}</p>
    <div class="hl-actions">
      <a class="cc-btn cc-btn-primary" href="#content_latest_products">Shop the collection</a>
      <a class="cc-btn cc-btn-secondary" href="index.php?_a=contact">Ask us a question</a>
    </div>
    <div class="hl-promises">
${promises}
    </div>
  </div>
</div>
`;
}

async function walk(dir, base = dir) {
  const out = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full, base)));
    else out.push(path.relative(base, full).split(path.sep).join("/"));
  }
  return out;
}

/**
 * @returns { folder, files: [{ path, content: Buffer }] } — paths are inside `folder`.
 */
export async function buildCubecartSkin({ site, slug, mediaDir }) {
  const folder = `eka-${String(slug).replace(/[^a-z0-9-]/g, "").slice(0, 40) || "site"}`;
  const files = [];
  const add = (p, content) => files.push({ path: `${folder}/${p}`, content: Buffer.isBuffer(content) ? content : Buffer.from(content) });

  // Logo: becomes the skin's default logo (PNG), so it shows without any admin setup.
  let logo = null;
  const m = String(site.header.logoImage || "").match(/^\/_m\/[^/]+\/([\w.-]+)$/);
  if (m && mediaDir) {
    try {
      const raw = await fs.readFile(path.join(mediaDir, m[1]));
      logo = sharp ? await sharp(raw).resize({ height: 160, withoutEnlargement: true }).png().toBuffer() : /\.png$/i.test(m[1]) ? raw : null;
    } catch {
      logo = null;
    }
  }

  // Safe inside CDATA and as a String.replace replacement.
  const name = site.name.replace(/]]>/g, "").replace(/\$/g, "$$$$");
  for (const rel of await walk(BASE)) {
    if (SKIP.has(rel)) continue;
    if (/^css\/cubecart\.(oxblood|navy|walnut)\.css$/.test(rel)) continue;
    let content = await fs.readFile(path.join(BASE, rel));
    if (rel === "config.xml") {
      let xml = content.toString();
      xml = xml.replace("<uid>heirloom-1.0@ekahosting</uid>", `<uid>${folder}@ekahosting</uid>`)
        .replace("<name><![CDATA[heirloom]]></name>", `<name><![CDATA[${folder}]]></name>`)
        .replace("<display><![CDATA[Heirloom]]></display>", `<display><![CDATA[${name} (EKA)]]></display>`)
        .replace(/<description><!\[CDATA\[[\s\S]*?\]\]><\/description>/, `<description><![CDATA[The ${name} design from EKA Hosting, on the Heirloom skin.]]></description>`)
        // One colour scheme: the site's own.
        .replace(/<styles>[\s\S]*?<\/styles>/, `<styles>\n\t<style images="false" default="true">\n\t  <directory>default</directory>\n\t  <name><![CDATA[${name}]]></name>\n\t  <description><![CDATA[Colours from the EKA design]]></description>\n\t  <default />\n\t</style>\n  </styles>`);
      content = Buffer.from(xml);
    }
    if (rel === "templates/element.css.php") {
      content = Buffer.from(content.toString()
        // The Heirloom heading font isn't used by this design: don't preload it.
        .replace(/<link rel="preload"[^>]*cormorant[^>]*>\n?/, "")
        .replace(/(<link rel="stylesheet" href="\{\$ROOT_PATH\}skins\/\{\$SKIN_FOLDER\}\/css\/heirloom\.css\?v=\{\$CSS_VERSION\}">)/, `$1\n{* The colours, fonts and rounding from the EKA design. *}\n<link rel="stylesheet" href="{$ROOT_PATH}skins/{$SKIN_FOLDER}/css/eka-theme.css?v={$CSS_VERSION}">`));
    }
    if (logo && (rel === "templates/main.php" || rel === "templates/main.checkout.php")) {
      // The design's logo ships as the skin's default logo, so show it.
      content = Buffer.from(content.toString().replace("{if empty($STORE_LOGO) || $STORE_LOGO|strpos:'/images/default/logo/default.png' !== false}", "{if empty($STORE_LOGO)}"));
    }
    if (logo && rel === "images/default/logo/default.png") content = logo;
    add(rel, content);
  }

  add("css/eka-theme.css", themeCss(site));
  add("docs/HOMEPAGE.html", homepageHtml(site));
  add("INSTALL.md", installNotes(site, folder, !!logo));
  return { folder, files };
}

function installNotes(site, folder, hasLogo) {
  return `# ${site.name}: CubeCart skin from EKA Hosting

This skin gives a CubeCart 6.8+ shop the look of the "${site.name}" design made in
EKA Hosting: colours, fonts, corner rounding${hasLogo ? " and logo" : ""}. It's built on the Heirloom
skin, so every product is treated as one of a kind (no quantity boxes, "Sold" stamps
on anything out of stock).

## Install

1. In your hosting's file manager, open the CubeCart folder, then \`skins/\`.
2. Upload this ZIP and extract it, so you have \`skins/${folder}/\`.
3. In the CubeCart admin, choose **${site.name} (EKA)** as the storefront skin and save.

## Homepage

Open the homepage document in the CubeCart admin, switch the editor to **Source**,
and paste in \`docs/HOMEPAGE.html\`. Tick "hide title" on that document.

## Changing the design

Change the design in EKA Hosting, then download the skin again and upload it over
this one. Your own CSS tweaks belong in \`css/custom.css\` (keep a copy: re-uploading
replaces it).

## Credits

Built on Heirloom (EKA Hosting) and Atrium (CubeCart), GPL-3.0. Fonts: see \`fonts/\`.
`;
}
